#!/usr/bin/env bash
# Mario Madness shader ports (TODO.md §23.2 "Shaders"): compile the nine new
# Shader/Effect pairs plus shaders/EffectTicker.hx unchanged, then run their
# contract spec in the Haxe interpreter. No game haxelibs needed.
#
# The interesting part is the generated stub. A FlxShader gets one field per GLSL
# uniform from the @:glFragmentSource macro, so a hand-written stub would happily
# accept `shader.uStatc.value = [0.05]` for a uniform the GLSL never declares -
# the exact typo class that ships as a silent no-op. This script parses the
# `uniform` declarations out of the shader sources and writes
# backend/FlxFixedShader.hx from them, so a Haxe field with no GLSL uniform is a
# compile error here, while RetroShadersSpec checks the other direction (a GLSL
# uniform no constructor initializes).
set -euo pipefail
root=$(cd "$(dirname "$0")/../.." && pwd)
cd "$root"

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

mkdir -p "$work/shaders" "$work/backend"

# Production files under test, copied verbatim.
cp source/shaders/Effect.hx "$work/shaders/"
cp source/shaders/EffectTicker.hx "$work/shaders/"
for shader in CRT OldTV TVStatic Ripple Silhouette Mosaic BrightnessContrast VCRBorder VCRFuzz; do
  cp "source/shaders/${shader}Shader.hx" "$work/shaders/"
  cp "source/shaders/${shader}Effect.hx" "$work/shaders/"
done

# Renderer-free stubs for the surfaces those files touch.
cp -R tests/haxe/stubs/retro-shaders/. "$work/"

# Collect "type name" for every uniform the nine shaders declare, comments
# stripped so prose cannot invent a uniform.
declarations=$(
  sed 's://.*::' "$work"/shaders/*Shader.hx |
    grep -oE 'uniform[[:space:]]+(float|bool|int|vec2|vec3|vec4)[[:space:]]+[A-Za-z_][A-Za-z0-9_]*[[:space:]]*;' |
    sed -E 's/^uniform[[:space:]]+//; s/[[:space:]]*;$//' |
    sort -u
)

if [ -z "$declarations" ]; then
  echo "FAIL: no uniform declarations found in the shaders under test" >&2
  exit 1
fi

# One field per name: the same uniform name in two shaders must mean the same
# type, or the shared stub could hide a mismatch.
conflict=$(printf '%s\n' "$declarations" | awk '{ seen[$2] = $2 " " $1; if (count[$2]++ && prev[$2] != $1) print $2 ": " prev[$2] " vs " $1; prev[$2] = $1 }')
if [ -n "$conflict" ]; then
  echo "FAIL: uniform declared with two types: $conflict" >&2
  exit 1
fi

stub="$work/backend/FlxFixedShader.hx"
{
  echo 'package backend;'
  echo
  echo 'import flixel.system.FlxAssets.FlxShader as OriginalFlxShader;'
  echo
  echo '// GENERATED by tests/haxe/run-retro-shaders.sh from the `uniform` declarations'
  echo '// in the shader sources: one field per uniform, all left uninitialized so the'
  echo '// spec can tell a shader that never sets one. Do not edit, do not commit.'
  echo 'class FlxFixedShader extends OriginalFlxShader'
  echo '{'
  printf '%s\n' "$declarations" | while read -r type name; do
    case "$type" in
      bool) haxe_type='Array<Bool>' ;;
      int) haxe_type='Array<Int>' ;;
      *) haxe_type='Array<Float>' ;;
    esac
    echo "  public var $name:{value:$haxe_type};"
  done
  echo
  echo '  public function new(?save:Bool)'
  echo '  {'
  echo '    super();'
  printf '%s\n' "$declarations" | while read -r type name; do
    echo "    $name = {value: null};"
  done
  echo '  }'
  echo '}'
} >"$stub"

echo "Generated the uniform stub with $(printf '%s\n' "$declarations" | wc -l | tr -d ' ') uniforms."

"${HAXE:-haxe}" -cp "$work" -cp "$root/tests/haxe" -main RetroShadersSpec --interp
